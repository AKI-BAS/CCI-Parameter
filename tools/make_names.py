# -*- coding: utf-8 -*-
"""tools/names_is.tsv -> src/data/names_is.json (shipped Icelandic names).

A '*' after a name marks BIM Ísland's own term (status "bim_island");
everything else is a draft. Each entry remembers the English term it was
translated from, so a later table where the English changed shows the
Icelandic name as "stale" (needs a look).
"""
from __future__ import print_function, unicode_literals

import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "src", "data")


def main():
    default = json.load(io.open(os.path.join(DATA, "default.json"),
                                 encoding="utf-8"))
    table = json.load(io.open(os.path.join(
        DATA, "tables", default["active_table"] + ".json"), encoding="utf-8"))
    names, unknown = {}, []
    for line in io.open(os.path.join(HERE, "names_is.tsv"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        key, name = cols[0], cols[1]
        # optional third column: other words people search with,
        # comma separated (e.g. "handlaug, baðkar" for Vaskur)
        also = [w.strip() for w in cols[2].split(",")] \
            if len(cols) > 2 and cols[2].strip() else []
        status = "draft"
        if name.endswith("*"):
            name, status = name[:-1], "bim_island"
        parts = key.split(":")
        if parts[0] == "group":
            entry = table["groups"].get(parts[1], {}).get(parts[2])
        else:
            entry = table["domains"].get(parts[0], {}).get(parts[1])
        if entry is None:
            unknown.append(key)
            continue
        names[key] = {"is": name, "en": entry.get("en", ""),
                      "status": status}
        if also:
            names[key]["also"] = also
    if unknown:
        print("not in table:", unknown)
        sys.exit(1)
    out = {"_about": "Icelandic names for CCI classes. 'draft' = not yet "
                     "reviewed; 'bim_island' "
                     "= BIM Ísland's own term. Generated by "
                     "tools/make_names.py.",
           "table": default["active_table"], "names": names}
    with io.open(os.path.join(DATA, "names_is.json"), "w",
                 encoding="utf-8") as f:
        f.write(json.dumps(out, ensure_ascii=False, indent=1,
                           sort_keys=True))
    print(len(names), "names")


if __name__ == "__main__":
    main()
